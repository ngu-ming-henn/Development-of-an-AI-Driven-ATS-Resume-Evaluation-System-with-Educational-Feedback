"""Rebuild backend/ocr_known_words.txt, the list of ordinary resume words that OCR
correction must leave alone.

The words come from the filtered resume dataset (outputs/resume_dataset_filter/
Resume_CS_Only.csv, kept out of Git). Only words used at least twice are kept, so
typos in a single resume are not treated as real words. The file holds single
lower-case words only, no resume text.

Usage: python tools/build_ocr_known_words.py
"""

from __future__ import annotations

import csv
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "outputs" / "resume_dataset_filter" / "Resume_CS_Only.csv"
TARGET = ROOT / "backend" / "ocr_known_words.txt"


def main() -> None:
    csv.field_size_limit(10**8)
    counts: Counter[str] = Counter()
    with SOURCE.open(encoding="utf-8", errors="replace") as handle:
        for row in csv.DictReader(handle):
            text = row.get("Resume_str") or ""
            counts.update(token.lower() for token in re.findall(r"[A-Za-z][A-Za-z'-]*[A-Za-z]", text))
    words = sorted(word for word, count in counts.items() if count >= 2 and 2 <= len(word) <= 30)
    TARGET.write_text(
        "# Ordinary resume words that OCR correction leaves alone.\n"
        "# Generated by tools/build_ocr_known_words.py; one lower-case word per line.\n"
        + "\n".join(words)
        + "\n",
        encoding="utf-8",
    )
    print(f"{len(words)} words written to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
